#!/usr/bin/env node
/**
 * Inline the SQL migration files into a generated TypeScript module.
 *
 * The `.sql` files are the single source of truth: the Rust shell reads that
 * directory with `include_dir!` at compile time, and this script produces the
 * TypeScript equivalent so the same text is available to the vitest harness and
 * to any bundler target without a filesystem. Neither side can drift, because
 * neither side has its own copy of the schema.
 *
 * Run automatically by the package's `build` and `test` scripts.
 */
import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const migrationsDir = join(here, '..', 'migrations', 'sqlite');
const outFile = join(here, '..', 'src', 'generated', 'migrations.gen.ts');
const defaultsFile = join(here, '..', 'seeds', 'default-categories.json');
const defaultsOut = join(here, '..', 'src', 'generated', 'default-categories.gen.ts');

const files = (await readdir(migrationsDir)).filter((name) => name.endsWith('.sql')).sort();

if (files.length === 0) {
  throw new Error(`No .sql migrations found in ${migrationsDir}`);
}

const entries = [];
for (const file of files) {
  const match = /^(\d+)_(.+)\.sql$/.exec(file);
  if (!match) {
    throw new Error(`Migration file name must be <version>_<name>.sql, got: ${file}`);
  }
  const [, version, name] = match;
  const sql = await readFile(join(migrationsDir, file), 'utf8');
  entries.push({ version: Number(version), name: `${version}_${name}`, sql });
}

// Backtick, backslash and `${` are the only sequences that can break out of a
// template literal; escaping them keeps the SQL byte-identical otherwise.
const escape = (sql) => sql.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');

const body = entries
  .map(
    (entry) => `  {
    version: ${entry.version},
    name: ${JSON.stringify(entry.name)},
    sql: \`${escape(entry.sql)}\`,
  },`,
  )
  .join('\n');

const output = `// Generated by scripts/generate-migrations.mjs — do not edit.
// Source of truth: packages/database/migrations/sqlite/*.sql

export interface GeneratedMigration {
  version: number;
  name: string;
  sql: string;
}

export const GENERATED_MIGRATIONS: readonly GeneratedMigration[] = [
${body}
];
`;

await mkdir(dirname(outFile), { recursive: true });
await writeFile(outFile, output, 'utf8');

console.error(`Generated ${outFile} from ${entries.length} migration(s).`);

// The default categories are seeded into a fresh database by the Rust layer
// (`include_str!` on the same JSON) and into the browser demo by the seed
// loader. One file, two readers, no drift.
const defaults = JSON.parse(await readFile(defaultsFile, 'utf8'));
await writeFile(
  defaultsOut,
  `// Generated by scripts/generate-migrations.mjs — do not edit.
// Source of truth: packages/database/seeds/default-categories.json

import type { CategoryRule } from '@yanuka/types';

export interface DefaultCategory {
  name: string;
  description: string;
  icon: string;
  color: string;
  showOnHome: boolean;
  rule: CategoryRule;
}

export const DEFAULT_CATEGORIES: readonly DefaultCategory[] = ${JSON.stringify(defaults, null, 2)};
`,
  'utf8',
);
console.error(`Generated ${defaultsOut} from ${defaults.length} default categories.`);
